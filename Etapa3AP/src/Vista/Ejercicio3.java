    private void btnAgregarProductoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnAgregarProductoMouseClicked
        if (this.cbxProductos.getSelectedItem().toString().equals("Seleccione una categoria")) {
            JOptionPane.showMessageDialog(rootPane, "Seleccione una categoria!");
        } else {
            if (this.tfArticulo.getText().isEmpty()) {
                JOptionPane.showMessageDialog(rootPane, "Ingrese un articulo!");
            } else {
                if (this.tfPrecio.getText().isEmpty()) {
                    JOptionPane.showMessageDialog(rootPane, "Ingrese un precio!");
                } else {
                    Articulo articulo = new Articulo();

                    articulo.setNombre(this.tfArticulo.getText());
                    articulo.setPrecio(Double.valueOf(this.tfPrecio.getText()));
                    articulo.setCategoria(this.cbxProductos.getSelectedItem().toString());

                    articulos.add(articulo);
                   
                   // model.addRow(new Object[]{articulo.getNombre(), articulo.getCategoria(), articulo.getPrecio()});
                   
                    this.eliminarFilas();
                    this.cargarDatosSegunCategoria();
                }
            }

        }


    }//GEN-LAST:event_btnAgregarProductoMouseClicked

    private void cbxProductosItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cbxProductosItemStateChanged
     if (!this.cbxProductos.getSelectedItem().toString().equals("Seleccione una categoria")) {
            eliminarFilas();
            cargarDatosSegunCategoria();
        }
    }//GEN-LAST:event_cbxProductosItemStateChanged

