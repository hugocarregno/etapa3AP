    public void cargarDatosSegunCategoria() {
        for (Articulo art : articulos) {
            if (this.cbxProductos.getSelectedItem().toString().equals(art.getCategoria())) {
                model.addRow(new Object[]{art.getNombre(), art.getCategoria(), art.getPrecio()});
            }
        }

    }

    public void eliminarFilas() {
        while (model.getRowCount() > 0) {
            int i = model.getRowCount();
            model.removeRow(i - 1);
        }
    }
    


