    private void jbNuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbNuevoActionPerformed
        if(!vacio()){
            Producto p = new Producto(
                Integer.parseInt(jtfCodigo.getText()),
                jtfDescripcion.getText(),
                Double.parseDouble(jtfPrecio.getText()),
                Integer.parseInt(jtfStock.getText()),
                (Modelo.Categoria) jcbRubro.getSelectedItem()
            );
            Ejercicio4.productos.add(p);
        } else {
            JOptionPane.showMessageDialog(null, "No puede haber campos vacios");
        }
        
    }//GEN-LAST:event_jbNuevoActionPerformed

    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbGuardarActionPerformed
        if(!vacio()){
            List<Producto> p = Ejercicio4.productos.stream()
                .filter(i-> i.getCodigo() == Integer.parseInt(jtfCodigo.getText()))
                .collect(Collectors.toList());
            if(!p.isEmpty()){
                p.get(0).setDescripcion(jtfDescripcion.getText());
                p.get(0).setPrecio(Double.parseDouble(jtfPrecio.getText()));
                p.get(0).setStock(Integer.parseInt(jtfStock.getText()));
                p.get(0).setRubro((Modelo.Categoria)jcbRubro.getSelectedItem());
                JOptionPane.showMessageDialog(null, "Cambios Guardados");
            } else {
                JOptionPane.showMessageDialog(null, "No existe producto con ese codigo");
            }
            
        } else {
            JOptionPane.showMessageDialog(null, "No puede haber campos vacios");
        }
        
    }//GEN-LAST:event_jbGuardarActionPerformed

    private void jbBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbBuscarActionPerformed
        List<Producto> p = Ejercicio4.productos.stream()
                .filter(i-> i.getCodigo() == Integer.parseInt(jtfCodigo.getText()))
                .collect(Collectors.toList());
        if(!p.isEmpty()){
            jtfDescripcion.setText(p.get(0).getDescripcion());
            jtfStock.setText(p.get(0).getStock()+"");
            jtfPrecio.setText(p.get(0).getPrecio()+"");
            jcbRubro.setSelectedItem(p.get(0).getRubro());
        } else {
            JOptionPane.showMessageDialog(null, "No existe producto con ese codigo");
        }
    }//GEN-LAST:event_jbBuscarActionPerformed

    private void jbSalirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbSalirActionPerformed
        dispose();
    }//GEN-LAST:event_jbSalirActionPerformed

    private void jbEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEliminarActionPerformed
        Ejercicio4.productos.removeIf(
            i-> i.getCodigo() == Integer.parseInt(jtfCodigo.getText())
        );
        JOptionPane.showMessageDialog(null, "Producto eliminado");
        limpiar();
    }//GEN-LAST:event_jbEliminarActionPerformed

    private void jtfStockKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jtfStockKeyTyped
        if(!Character.isDigit(evt.getKeyChar())){
            evt.consume();
        }
    }//GEN-LAST:event_jtfStockKeyTyped

    private void jtfCodigoKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jtfCodigoKeyTyped
        if(!Character.isDigit(evt.getKeyChar())){
            evt.consume();
        }
    }//GEN-LAST:event_jtfCodigoKeyTyped

    private void jtfPrecioKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jtfPrecioKeyTyped
        if(!Character.isDigit(evt.getKeyChar()) && evt.getKeyChar() != '.'){
            evt.consume();
        }
    }//GEN-LAST:event_jtfPrecioKeyTyped
    
    private void limpiar(){
        jtfCodigo.setText("");
        jtfDescripcion.setText("");
        jtfPrecio.setText("");
        jtfStock.setText("");
        jcbRubro.setSelectedIndex(0);
    }
    
    private boolean vacio(){
        return jtfCodigo.getText().equals("") ||
               jtfDescripcion.getText().equals("") ||
               jtfStock.getText().equals("") ||
               jtfPrecio.getText().equals("");
    }
